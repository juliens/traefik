// Command nativeplugins compiles the plugins of Traefik (the plugins module) into Traefik:
// with -builtin, it generates the file registering all of them,
// with their manifest and their functions (CreateConfig and New, or New<Option> for the options of the dynamic configuration they implement).
//
// With -providers, it also generates the types of the options of the providers in the static configuration (providers.docker, ...),
// from the configurations of the provider plugins implementing them (see the providerconf package).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/rs/zerolog/log"
	"gopkg.in/yaml.v3"
)

const pluginsModule = "github.com/traefik/traefik/v3/plugins"

// manifest is the part of the manifest of a plugin (.traefik.yml) that tells its functions.
type manifest struct {
	Type       string   `yaml:"type"`
	Import     string   `yaml:"import"`
	Implements []string `yaml:"implements"`
}

// plugin is a plugin of the plugins module.
type plugin struct {
	manifest

	// moduleName is the module name of the plugin in experimental.localPlugins: the path of the directory of its manifest.
	moduleName string
	content    string
	functions  []string
}

func main() {
	pluginsDir := flag.String("plugins", "plugins", "directory of the plugins module")
	builtin := flag.String("builtin", "", "generated file registering the plugins into Traefik")
	providers := flag.String("providers", "", "generated file of the types of the options of the providers in the static configuration")
	flag.Parse()

	if err := run(*pluginsDir, *builtin, *providers); err != nil {
		log.Fatal().Err(err).Send()
	}
}

func run(pluginsDir, builtin, providers string) error {
	plugins, err := findPlugins(pluginsDir)
	if err != nil {
		return err
	}

	if builtin != "" {
		if err := generateBuiltin(builtin, plugins); err != nil {
			return err
		}
	}

	if providers != "" {
		return generateProviders(providers, plugins)
	}

	return nil
}

// findPlugins returns the plugins of the plugins module, sorted by module name.
func findPlugins(pluginsDir string) ([]plugin, error) {
	var plugins []plugin

	err := filepath.WalkDir(pluginsDir, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() && d.Name() == "vendor" {
			return filepath.SkipDir
		}

		if d.IsDir() || d.Name() != ".traefik.yml" {
			return nil
		}

		content, err := os.ReadFile(p)
		if err != nil {
			return err
		}

		var m manifest
		if err := yaml.Unmarshal(content, &m); err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}

		if !strings.HasPrefix(m.Import, pluginsModule+"/") {
			return fmt.Errorf("%s: the plugin %s is not in the plugins module", p, m.Import)
		}

		rel, err := filepath.Rel(pluginsDir, filepath.Dir(p))
		if err != nil {
			return err
		}

		// A provider plugin implementing an option of the providers takes its configuration as the other provider plugins.
		functions := []string{"CreateConfig", "New"}
		if m.Type == "middleware" && len(m.Implements) > 0 {
			functions = nil
			for _, option := range m.Implements {
				functions = append(functions, "New"+strings.ToUpper(option[:1])+option[1:])
			}
		}

		plugins = append(plugins, plugin{manifest: m, moduleName: pluginsModule + "/" + filepath.ToSlash(rel), content: string(content), functions: functions})

		return nil
	})

	slices.SortFunc(plugins, func(a, b plugin) int { return strings.Compare(a.moduleName, b.moduleName) })

	return plugins, err
}

// generateBuiltin writes the file registering the plugins into Traefik.
func generateBuiltin(file string, plugins []plugin) error {
	b := &bytes.Buffer{}
	fmt.Fprintln(b, "// Code generated by cmd/internal/nativeplugins. DO NOT EDIT.")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "package main")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "import (")
	fmt.Fprintln(b, `"github.com/traefik/traefik/v3/pkg/plugins"`)
	for i, p := range plugins {
		fmt.Fprintf(b, "p%d %q\n", i, p.Import)
	}
	fmt.Fprintln(b, ")")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "// The plugins of Traefik, compiled into Traefik: they run natively, and are found by their module name.")
	fmt.Fprintln(b, "func init() {")
	for i, p := range plugins {
		fmt.Fprintf(b, "plugins.RegisterBuiltin(%q, %s, map[string]any{\n", p.moduleName, strconv.Quote(p.content))
		for _, fn := range p.functions {
			fmt.Fprintf(b, "%q: p%d.%s,\n", fn, i, fn)
		}
		fmt.Fprintln(b, "})")
	}
	fmt.Fprintln(b, "}")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	log.Info().Int("plugins", len(plugins)).Str("file", file).Msg("Generated the registration of the builtin plugins")

	return os.WriteFile(file, src, 0o644)
}

// providerConfDir is the directory of the generated program writing the types of the options of the providers:
// it imports the provider plugins, to read their configurations.
// It is under cmd/, to import the providerconf package, and go ./... patterns skip it.
const providerConfDir = "cmd/internal/nativeplugins/_providerconf"

// generateProviders writes the types of the options of the providers in the static configuration,
// from the configurations of the provider plugins implementing them.
func generateProviders(file string, plugins []plugin) error {
	b := &bytes.Buffer{}
	fmt.Fprintln(b, "// Code generated by cmd/internal/nativeplugins. DO NOT EDIT.")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "package main")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "import (")
	fmt.Fprintln(b, `"os"`)
	fmt.Fprintln(b, `"github.com/traefik/traefik/v3/cmd/internal/nativeplugins/providerconf"`)

	var providers []string
	for i, p := range plugins {
		if p.Type != "provider" {
			continue
		}

		for _, option := range p.Implements {
			providers = append(providers, fmt.Sprintf("{Option: %q, Import: %q, Config: p%d.CreateConfig()},", option, p.Import, i))
		}

		if len(p.Implements) > 0 {
			fmt.Fprintf(b, "p%d %q\n", i, p.Import)
		}
	}

	fmt.Fprintln(b, ")")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "func main() {")
	fmt.Fprintln(b, `src, err := providerconf.Generate("static", []providerconf.Provider{`)
	for _, p := range providers {
		fmt.Fprintln(b, p)
	}
	fmt.Fprintln(b, "})")
	fmt.Fprintln(b, "if err != nil {")
	fmt.Fprintln(b, "_, _ = os.Stderr.WriteString(err.Error() + \"\\n\")")
	fmt.Fprintln(b, "os.Exit(1)")
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b)
	fmt.Fprintln(b, "if err := os.WriteFile(os.Args[1], src, 0o644); err != nil {")
	fmt.Fprintln(b, "_, _ = os.Stderr.WriteString(err.Error() + \"\\n\")")
	fmt.Fprintln(b, "os.Exit(1)")
	fmt.Fprintln(b, "}")
	fmt.Fprintln(b, "}")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}

	if err := os.MkdirAll(providerConfDir, 0o755); err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(providerConfDir) }()

	if err := os.WriteFile(filepath.Join(providerConfDir, "main.go"), src, 0o644); err != nil {
		return err
	}

	cmd := exec.Command("go", "run", "./"+providerConfDir, file)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	if err := cmd.Run(); err != nil {
		return fmt.Errorf("generating the types of the providers: %w", err)
	}

	log.Info().Int("providers", len(providers)).Str("file", file).Msg("Generated the types of the options of the providers")

	return nil
}
