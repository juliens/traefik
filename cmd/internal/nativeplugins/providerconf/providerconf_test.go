package providerconf

import (
	"testing"
	"time"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
	ptypes "github.com/traefik/paerser/types"
	"gopkg.in/yaml.v3"
)

type shared struct {
	Watch bool `json:"watch,omitempty"`
}

func TestGenerate(t *testing.T) {
	config := &struct {
		shared

		Endpoint string          `json:"endpoint,omitempty"`
		Refresh  ptypes.Duration `json:"refresh,omitempty"`
		Names    []string        `json:"names,omitempty"`
		Reuse    *bool           `json:"reuse,omitempty"`
		Internal string          `json:"-"`
	}{Watch: true, Refresh: ptypes.Duration(time.Second), Names: []string{"a"}, Reuse: new(true), Internal: "x"}

	src, err := Generate("static", []Provider{{Option: "http", Import: "example.com/http", Config: config}})
	require.NoError(t, err)

	expected := "// Code generated by cmd/internal/nativeplugins. DO NOT EDIT.\n\n" +
		"package static\n\n" +
		"import (\n\tptypes \"github.com/traefik/paerser/types\"\n)\n\n" +
		"// HTTPProvider is the configuration of the http provider, implemented by the plugin example.com/http.\n" +
		"type HTTPProvider struct {\n" +
		"\tWatch    bool            `json:\"watch,omitempty\"`\n" +
		"\tEndpoint string          `json:\"endpoint,omitempty\"`\n" +
		"\tRefresh  ptypes.Duration `json:\"refresh,omitempty\"`\n" +
		"\tNames    []string        `json:\"names,omitempty\"`\n" +
		"\tReuse    *bool           `json:\"reuse,omitempty\"`\n" +
		"}\n\n" +
		"// SetDefaults sets the default values.\n" +
		"func (p *HTTPProvider) SetDefaults() {\n" +
		"\tp.Watch = true\n" +
		"\tp.Refresh = ptypes.Duration(1000000000)\n" +
		"\tp.Names = []string{\"a\"}\n" +
		"\tp.Reuse = new(true)\n" +
		"}\n"

	assert.Equal(t, expected, string(src))
}

func TestGenerate_forbiddenImport(t *testing.T) {
	config := &struct {
		Node *yaml.Node `json:"node,omitempty"`
	}{}

	_, err := Generate("static", []Provider{{Option: "docker", Import: "example.com/docker", Config: config}})
	require.ErrorContains(t, err, "the static configuration must not import gopkg.in/yaml.v3")
}

func TestTypeName(t *testing.T) {
	assert.Equal(t, "DockerProvider", TypeName("docker"))
	assert.Equal(t, "HTTPProvider", TypeName("http"))
	assert.Equal(t, "ACMEResolver", TypeName("certificatesResolvers.acme"))
}
