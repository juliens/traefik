// Package providerconf generates the types of the options of the providers in the static configuration (providers.docker, ...),
// and of the certificates resolvers (certificatesResolvers.<name>.acme), from the configurations of the provider plugins implementing them.
//
// The static configuration keeps these options as they were before the providers and ACME became plugins:
// same names, same flags, same defaults. Its types are copies of the configuration types of the plugins,
// so that Traefik does not import the plugins, and the libraries they use (Docker, Kubernetes, ...).
// A copy may only use the types of the standard library, of Traefik (pkg/) and of paerser.
package providerconf

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"
	"slices"
	"strconv"
	"strings"
)

const pluginsModule = "github.com/traefik/traefik/v3/plugins/"

// ResolverPrefix is the prefix of the options of the certificates resolvers that a provider plugin implements:
// certificatesResolvers.acme for the certificatesResolvers.<name>.acme option.
const ResolverPrefix = "certificatesResolvers."

// Provider is a provider plugin implementing an option of the providers of the static configuration.
type Provider struct {
	// Option is the option implemented by the plugin: an option of the providers (docker, kubernetesCRD, ...),
	// or of the certificates resolvers (certificatesResolvers.acme).
	Option string
	// Import is the package of the plugin.
	Import string
	// Config is the result of the CreateConfig function of the plugin: its configuration, with the default values.
	Config any
}

// TypeName returns the name of the type of the given option: DockerProvider for docker, ACMEResolver for certificatesResolvers.acme.
func TypeName(option string) string {
	if name, ok := strings.CutPrefix(option, ResolverPrefix); ok {
		return exportedName(name) + "Resolver"
	}

	return exportedName(option) + "Provider"
}

func exportedName(option string) string {
	switch option {
	case "http":
		return "HTTP"
	case "acme":
		return "ACME"
	}

	return strings.ToUpper(option[:1]) + option[1:]
}

// Generate returns the source of the types of the given options of the providers, in the given package.
func Generate(pkg string, providers []Provider) ([]byte, error) {
	g := &generator{imports: map[string]string{}, names: map[reflect.Type]string{}}

	providers = slices.Clone(providers)
	slices.SortFunc(providers, func(a, b Provider) int { return strings.Compare(a.Option, b.Option) })

	for _, p := range providers {
		v := reflect.ValueOf(p.Config)
		if v.Kind() != reflect.Pointer || v.Elem().Kind() != reflect.Struct {
			return nil, fmt.Errorf("the configuration of the plugin %s is a %T, a pointer to a struct is expected", p.Import, p.Config)
		}

		if err := g.provider(p, v.Elem()); err != nil {
			return nil, fmt.Errorf("the plugin %s: %w", p.Import, err)
		}
	}

	b := &bytes.Buffer{}
	fmt.Fprintln(b, "// Code generated by cmd/internal/nativeplugins. DO NOT EDIT.")
	fmt.Fprintln(b)
	fmt.Fprintf(b, "package %s\n", pkg)
	fmt.Fprintln(b)

	paths := make([]string, 0, len(g.imports))
	for path := range g.imports {
		paths = append(paths, path)
	}
	slices.Sort(paths)

	fmt.Fprintln(b, "import (")
	for _, path := range paths {
		fmt.Fprintf(b, "%s %q\n", g.imports[path], path)
	}
	fmt.Fprintln(b, ")")
	fmt.Fprintln(b)

	b.Write(g.body.Bytes())

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated source: %w\n%s", err, b.String())
	}

	return src, nil
}

type generator struct {
	body bytes.Buffer
	// imports are the aliases of the imported packages, by path.
	imports map[string]string
	// names are the generated types, by type of the plugins.
	names map[reflect.Type]string
	// pending are the types of the plugins used by the generated types, to generate.
	pending []reflect.Type
	// prefix is the prefix of the names of the generated types of the current provider: Docker for docker.
	prefix string
}

func (g *generator) provider(p Provider, v reflect.Value) error {
	option, isResolver := strings.CutPrefix(p.Option, ResolverPrefix)
	g.prefix = exportedName(option)
	name := TypeName(p.Option)

	if isResolver {
		fmt.Fprintf(&g.body, "// %s is the configuration of the %s certificates resolvers, implemented by the plugin %s.\n", name, option, p.Import)
	} else {
		fmt.Fprintf(&g.body, "// %s is the configuration of the %s provider, implemented by the plugin %s.\n", name, option, p.Import)
	}
	if err := g.structType(name, v.Type()); err != nil {
		return err
	}

	fmt.Fprintln(&g.body, "// SetDefaults sets the default values.")
	fmt.Fprintf(&g.body, "func (p *%s) SetDefaults() {\n", name)
	if err := g.defaults("p.", v); err != nil {
		return err
	}
	fmt.Fprintln(&g.body, "}")
	fmt.Fprintln(&g.body)

	for len(g.pending) > 0 {
		t := g.pending[0]
		g.pending = g.pending[1:]

		fmt.Fprintf(&g.body, "// %s is the %s type of %s.\n", g.names[t], t.Name(), name)
		if err := g.structType(g.names[t], t); err != nil {
			return err
		}
	}

	return nil
}

// fields returns the options of a configuration type: its exported fields,
// and the fields of its embedded structs, which are options of the type itself in the static configuration.
func fields(t reflect.Type) []reflect.StructField {
	var res []reflect.StructField
	for field := range t.Fields() {
		name, _, _ := strings.Cut(field.Tag.Get("json"), ",")
		if name == "-" {
			continue
		}

		// The exported fields of an embedded struct are promoted, even when the struct is not exported.
		if field.Anonymous && field.Type.Kind() == reflect.Struct && name == "" {
			for _, inner := range fields(field.Type) {
				inner.Index = append([]int{field.Index[0]}, inner.Index...)
				res = append(res, inner)
			}

			continue
		}

		if field.IsExported() {
			res = append(res, field)
		}
	}

	return res
}

func (g *generator) structType(name string, t reflect.Type) error {
	fmt.Fprintf(&g.body, "type %s struct {\n", name)
	for _, field := range fields(t) {
		typ, err := g.typeName(field.Type)
		if err != nil {
			return fmt.Errorf("the %s option: %w", field.Name, err)
		}

		fmt.Fprintf(&g.body, "%s %s `%s`\n", field.Name, typ, field.Tag)
	}
	fmt.Fprintln(&g.body, "}")
	fmt.Fprintln(&g.body)

	return nil
}

// typeName returns the name of the given type in the generated source.
func (g *generator) typeName(t reflect.Type) (string, error) {
	switch {
	case t.Kind() == reflect.Pointer:
		elem, err := g.typeName(t.Elem())
		return "*" + elem, err

	case t.Name() == "" && t.Kind() == reflect.Slice:
		elem, err := g.typeName(t.Elem())
		return "[]" + elem, err

	case t.Name() == "" && t.Kind() == reflect.Map:
		key, err := g.typeName(t.Key())
		if err != nil {
			return "", err
		}

		elem, err := g.typeName(t.Elem())
		return "map[" + key + "]" + elem, err

	case t.PkgPath() == "":
		return t.String(), nil

	case strings.HasPrefix(t.PkgPath(), pluginsModule):
		if t.Kind() != reflect.Struct {
			return "", fmt.Errorf("the type %s of the plugins module is not a struct", t)
		}

		if name, ok := g.names[t]; ok {
			return name, nil
		}

		name := g.prefix + t.Name()
		g.names[t] = name
		g.pending = append(g.pending, t)

		return name, nil

	case isAllowed(t.PkgPath()):
		return g.importAlias(t.PkgPath()) + "." + t.Name(), nil

	default:
		return "", fmt.Errorf("the type %s is not a type of the standard library, of Traefik or of paerser: the static configuration must not import %s", t, t.PkgPath())
	}
}

// isAllowed reports whether the static configuration may import the given package: the light packages that Traefik already imports.
func isAllowed(path string) bool {
	first, _, _ := strings.Cut(path, "/")

	return !strings.Contains(first, ".") ||
		strings.HasPrefix(path, "github.com/traefik/traefik/v3/pkg/") ||
		strings.HasPrefix(path, "github.com/traefik/paerser/")
}

func (g *generator) importAlias(path string) string {
	if alias, ok := g.imports[path]; ok {
		return alias
	}

	alias := path[strings.LastIndex(path, "/")+1:]
	if path == "github.com/traefik/paerser/types" {
		alias = "ptypes"
	}

	g.imports[path] = alias

	return alias
}

// defaults writes the statements setting the non-zero values of the given configuration.
func (g *generator) defaults(prefix string, v reflect.Value) error {
	for _, field := range fields(v.Type()) {
		fv := v.FieldByIndex(field.Index)
		if fv.IsZero() {
			continue
		}

		target := prefix + field.Name

		switch fv.Kind() {
		case reflect.Pointer:
			if fv.Elem().Kind() != reflect.Struct {
				value, err := g.literal(fv.Elem())
				if err != nil {
					return fmt.Errorf("the default value of the %s option: %w", field.Name, err)
				}

				fmt.Fprintf(&g.body, "%s = new(%s)\n", target, value)

				continue
			}

			typ, err := g.typeName(fv.Elem().Type())
			if err != nil {
				return err
			}

			fmt.Fprintf(&g.body, "%s = &%s{}\n", target, typ)
			if err := g.defaults(target+".", fv.Elem()); err != nil {
				return err
			}

		case reflect.Struct:
			if err := g.defaults(target+".", fv); err != nil {
				return err
			}

		default:
			value, err := g.literal(fv)
			if err != nil {
				return fmt.Errorf("the default value of the %s option: %w", field.Name, err)
			}

			fmt.Fprintf(&g.body, "%s = %s\n", target, value)
		}
	}

	return nil
}

// literal returns the Go literal of a value of a basic type, or of a slice of them.
func (g *generator) literal(v reflect.Value) (string, error) {
	typ, err := g.typeName(v.Type())
	if err != nil {
		return "", err
	}

	var lit string
	switch v.Kind() {
	case reflect.Bool:
		lit = strconv.FormatBool(v.Bool())
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		lit = strconv.FormatInt(v.Int(), 10)
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		lit = strconv.FormatUint(v.Uint(), 10)
	case reflect.Float32, reflect.Float64:
		lit = strconv.FormatFloat(v.Float(), 'g', -1, 64)
	case reflect.String:
		lit = strconv.Quote(v.String())
	case reflect.Slice:
		elems := make([]string, v.Len())
		for i := range v.Len() {
			if elems[i], err = g.literal(v.Index(i)); err != nil {
				return "", err
			}
		}

		return typ + "{" + strings.Join(elems, ", ") + "}", nil
	default:
		return "", fmt.Errorf("a %s is not supported", v.Kind())
	}

	if v.Type().Name() != "" && v.Type().PkgPath() != "" {
		return typ + "(" + lit + ")", nil
	}

	return lit, nil
}
